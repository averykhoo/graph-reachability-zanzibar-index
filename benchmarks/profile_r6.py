TARGETS = {
    'set-lookup': lambda a: target_set_lookup(a.scale, a.calls),
    'set-expand': lambda a: target_set_expand(a.scale, a.expands),
    'graph-lookup': lambda a: target_graph_lookup(a.graph_scale, a.calls),
    'graph-check': lambda a: target_graph_check(a.graph_scale, a.checks),
}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--target', default='all', choices=sorted(TARGETS) + ['all'])
    ap.add_argument('--scale', type=int, default=800, help='set-engine dataset scale')
    ap.add_argument('--graph-scale', type=int, default=200, help='graph dataset scale')
    ap.add_argument('--calls', type=int, default=200, help='lookup calls to profile')
    ap.add_argument('--checks', type=int, default=2000, help='check calls to time')
    ap.add_argument('--expands', type=int, default=200, help='expand calls to profile')
    ap.add_argument('--pop', type=int, default=20000, help='wide-workload population')
    ap.add_argument('--blocked', type=int, default=500, help='wide-workload blocked users')
    args = ap.parse_args()

    names = sorted(TARGETS) if args.target == 'all' else [args.target]
    for name in names:
        TARGETS[name](args)
    print()


if __name__ == '__main__':
    main()
