def target_graph_lookup(scale, calls):
    _banner(f'graph-lookup — demorgans_law_2/graph scale={scale}, '
            f'{calls} lookup calls   [R6-4, R6-5]')
    spec = sb.WORKLOADS['demorgans']
    widx, ntup = build_graph(spec['schema'], spec['shapes'], spec['gen'](scale))
    subs = spec['lookups'](scale, calls)

    from index_v4.models import ResidueV1
    from sqlmodel import select
    nres = len(widx.idx.session.exec(select(ResidueV1).where(
        ResidueV1.store_id == widx.idx.store_id)).all())
    print(f'  dataset: {ntup:,} raw tuples, {nres:,} residue rows in store')

    def work():
        n = 0
        for (sp, st, sn) in subs:
            n += sb._rsz(widx.lookup(sp, st, sn))
        return n

    total, stats, table = _profile(work)
    rows = _rows(stats)
    wall = max(ct for (_n, _t, ct) in rows.values()) if rows else 0.0

    res_n, res_t, res_c = _find(rows, func='_collect_residue_memberships', file_frag='index_v4/wildcard.py')
    js_n, js_t, js_c = _find(rows, func='loads', file_frag='json/__init__.py')
    cls_n, cls_t, cls_c = _find(rows, func='_classify_ids', file_frag='index_v4/wildcard.py')
    ln_n, ln_t, ln_c = _find(rows, func='_load_nodes', file_frag='index_v4/core.py')
    lr_n, lr_t, lr_c = _find(rows, func='lookup_reachable', file_frag='index_v4/core.py')

    print(f'\n  results returned      : {total:,}')
    print(f'  wall (profiled)       : {wall:.2f} s   ({calls / wall:,.1f} lookups/s under profiler)')
    print(f'  _collect_residue_...  : {res_n:,} calls, {res_c:.3f} s cum  ({_pct(res_c, wall)})')
    print(f'  json.loads calls      : {js_n:,}  ({js_n / max(calls, 1):,.1f} per lookup, '
          f'{js_t:.3f} s self)')
    print(f'  residue rows in store : {nres:,}   -> expected full-scan rows/lookup: {nres:,}')
    print(f'  lookup_reachable      : {lr_n:,} calls, {lr_c:.3f} s cum  ({_pct(lr_c, wall)})')
    print(f'  _classify_ids         : {cls_n:,} calls, {cls_c:.3f} s cum  ({_pct(cls_c, wall)})')
    print(f'  _load_nodes           : {ln_n:,} calls, {ln_c:.3f} s cum  ({_pct(ln_c, wall)})')
    print('\n' + table)

    _verdict('R6-4',
             'lookup full-scans every residue row and JSON-decodes per row',
             f'{_pct(res_c, wall)} of lookup wall time, {js_n / max(calls, 1):,.1f} json.loads per lookup'
             + (f' over {nres:,} residue rows' if nres else ' (NO residue rows in this store)'),
             None if nres == 0 else res_c / wall > 0.15)
    _verdict('R6-5',
             'lookup fetches full Edge ORM rows then re-fetches full Node rows to classify',
             f'lookup_reachable {_pct(lr_c, wall)}, _classify_ids {_pct(cls_c, wall)}, '
             f'_load_nodes {_pct(ln_c, wall)}',
             (lr_c + cls_c) / wall > 0.20 if wall else None)
    return {'wall': wall, 'residue_rows': nres, 'json_loads': js_n}


