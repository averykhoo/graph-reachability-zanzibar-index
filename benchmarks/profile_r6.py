# ---------------------------------------------------------------------------
# Reporting helpers
# ---------------------------------------------------------------------------

def _profile(fn, *, sort='tottime', top=18):
    """Run fn() under cProfile; return (result, stats, printed_table)."""
    pr = cProfile.Profile()
    pr.enable()
    result = fn()
    pr.disable()
    st = pstats.Stats(pr)
    buf = StringIO()
    st.stream = buf
    st.sort_stats(sort).print_stats(top)
    return result, st, buf.getvalue()


def _rows(st):
    """{(file, line, func): (ncalls, tottime, cumtime)} from a pstats.Stats."""
    out = {}
    for key, val in st.stats.items():
        cc, nc, tt, ct, _callers = val
        out[key] = (nc, tt, ct)
    return out


def _find(rows, *, func, file_frag=None):
    """Sum (ncalls, tottime, cumtime) over entries matching a function name."""
    n = t = c = 0
    for (fname, _lineno, f), (nc, tt, ct) in rows.items():
        if f != func:
            continue
        if file_frag and file_frag not in fname.replace('\\', '/'):
            continue
        n += nc
        t += tt
        c = max(c, ct)          # cumtime does not sum across recursive entries
    return n, t, c


def _pct(part, whole):
    return f'{100.0 * part / whole:5.1f}%' if whole else '  n/a'


def _banner(title):
    print()
    print('=' * 78)
    print(title)
    print('=' * 78)


def _verdict(rid, claim, measured, motivated):
    tag = 'MOTIVATED' if motivated is True else ('NOT MOTIVATED' if motivated is False else 'INCONCLUSIVE')
    print(f'  [{rid}] {tag}')
    print(f'        claim   : {claim}')
    print(f'        measured: {measured}')


# ---------------------------------------------------------------------------
# SQL statement counting (same mechanism as stmt_bench)
# ---------------------------------------------------------------------------

class StmtCounter:
    """Counts SQL statements executed on a session's engine, bucketed by table."""

    def __init__(self, session):
        self.bind = session.get_bind()
        self.counts = Counter()
        self.total = 0
        self._on = False

        def _listen(conn, cursor, statement, params, context, executemany):
            if not self._on:
                return
            self.total += 1
            s = ' '.join(statement.split())
            if 'node_v4' in s and 'edge_v4' not in s:
                self.counts['node_v4'] += 1
            elif 'edge_v4' in s:
                self.counts['edge_v4'] += 1
            elif 'residue' in s:
                self.counts['residue'] += 1
            else:
                self.counts['other'] += 1

        event.listen(self.bind, 'before_cursor_execute', _listen)

    def start(self):
        self.counts.clear()
        self.total = 0
        self._on = True

    def stop(self):
        self._on = False


