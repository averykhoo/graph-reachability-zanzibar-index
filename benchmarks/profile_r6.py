def target_set_lookup(scale, calls):
    _banner(f'set-lookup — gdrive/set:roaring scale={scale}, {calls} lookup calls   [R6-1, R6-3]')
    # Use the reviewed WORKLOADS spec, not a hand-rolled call: gdrive declares object
    # wildcard shapes {(doc,viewer),(folder,viewer)}, and dropping them would silently
    # disable the very star branch R6-3 is about.
    spec = sb.WORKLOADS['gdrive']
    se, ntup = build_set(spec['schema'], spec['shapes'], RoaringSets, spec['gen'](scale))
    subs = sb.gdrive_lookups(scale, calls)
    print(f'  dataset: {ntup:,} raw tuples, {len(se.interner.key_of):,} interned keys')

    def work():
        n = 0
        for (sp, st, sn) in subs:
            n += sb._rsz(se.lookup(sp, st, sn))
        return n

    total, stats, table = _profile(work)
    rows = _rows(stats)
    wall = max(ct for (_n, _t, ct) in rows.values()) if rows else 0.0

    chk_n, chk_t, chk_c = _find(rows, func='check', file_frag='setengine/engine.py')
    inst_n, inst_t, inst_c = _find(rows, func='_instances_of_type', file_frag='setengine/engine.py')
    drive_n, _dt, _dc = _find(rows, func='_drive', file_frag='setengine/engine.py')

    print(f'\n  results returned      : {total:,}')
    print(f'  wall (profiled)       : {wall:.2f} s   ({calls / wall:,.1f} lookups/s under profiler)')
    print(f'  SetEngine.check calls : {chk_n:,}  ({chk_n / calls:,.1f} per lookup)')
    print(f'  ...cumulative time    : {chk_c:.2f} s  ({_pct(chk_c, wall)} of lookup)')
    print(f'  _drive invocations    : {drive_n:,}  ({drive_n / max(chk_n, 1):,.2f} per check)')
    print(f'  _instances_of_type    : {inst_n:,} calls, {inst_t:.3f} s self, {inst_c:.3f} s cum'
          f'  ({_pct(inst_c, wall)})')
    print('\n' + table)

    _verdict('R6-1',
             'lookup re-runs check with a fresh memo per candidate: O(candidates x chain-depth)',
             f'{chk_n / calls:,.1f} check calls per lookup, {_pct(chk_c, wall)} of lookup wall time',
             chk_n / calls > 5 and chk_c / wall > 0.5 if wall else None)
    _verdict('R6-3',
             '_instances_of_type scans the whole interner per type, repeated per check',
             f'{inst_n:,} calls, {_pct(inst_c, wall)} of lookup wall time'
             + ('  (star branch never fires on this workload)' if inst_n == 0 else ''),
             None if inst_n == 0 else inst_c / wall > 0.10)
    return {'wall': wall, 'check_calls': chk_n, 'check_cum': chk_c, 'inst_calls': inst_n}


