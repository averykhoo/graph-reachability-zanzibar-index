"""Round-6 MOTIVATING-MEASUREMENT profiler — attributes cost to R6-N candidate ids.

`docs/perf-round6-audit-2026-08.md` is a list of 18 code-verified but **unmeasured**
findings, and `docs/perf-next-round.md`'s reopening rule says each one needs a
motivating measurement before it is worth landing: the audit confirms the code *does*
the inefficient thing, not that the inefficiency *dominates*. Round 5 declined two
plausible candidates on exactly this kind of fresh profile.

A top-20 cProfile table does not answer that question on its own — it tells you where
time went, not whether the named fix would have moved it. So each target below pairs
the profile with **targeted counters** keyed to the candidate's own claim:

  set-lookup   (gdrive, set engine)      R6-1  check-calls per lookup, and the share of
                                               lookup time inside SetEngine.check
                                         R6-3  _instances_of_type calls + cumtime
  set-expand   (wide/star, set engine)   R6-2  ms.union / _starpop / _normalize calls
                                               and their share of expand time
                                         R6-3  the star branch actually firing
  graph-lookup (demorgans, graph index)  R6-4  _collect_residue_memberships share,
                                               json.loads calls + ResidueV1 rows scanned
                                         R6-5  EdgeV4/NodeV4 ORM rows instantiated
  graph-check  (gdrive, graph index)     R6-6  SQL statements per check(), split into
                                               node-resolution vs the batched edge probe

Additive tooling only: touches no production code, writes no `scale_bench.jsonl`, and
imports the existing generators from `scale_bench` / `set_engine_bench` rather than
re-inventing datasets (their shapes are already the reviewed ones).

⚠ Never run this next to another bench or a pytest run — CPU contention corrupts the
wall-clock column (`perf-next-round.md`, measurement hygiene). The COUNTERS are
contention-immune; the seconds are not.

Run:

    python -m benchmarks.profile_r6 --target set-lookup   --scale 800
    python -m benchmarks.profile_r6 --target set-expand   --pop 20000
    python -m benchmarks.profile_r6 --target graph-lookup --scale 200
    python -m benchmarks.profile_r6 --target graph-check  --scale 400
    python -m benchmarks.profile_r6 --target all

Deterministic: every dataset is generated by modular arithmetic, no RNG.
"""

