def target_set_expand(scale, calls):
    """R6-2 on the surface its own verifier named: expand / lookup_reverse.

    ⚠ The first version of this probe used set_engine_bench's wide/star schema
    (`viewer: public but not blocked`) and reported R6-2 NOT MOTIVATED at 18.8%
    algebra time. That verdict was an artifact of the instrument, not a measurement
    of the finding: on that schema `viewer` is star-CLOSED, so the answer lives in
    `stars`/`neg` and `direct_expand` folds a bitmap leaf in ONE union — 240 unions
    for 120 expands, i.e. the per-element fold R6-2 is about never ran, and `.pos`
    was empty so the probe also returned 0 members. R6-2 is about accumulating per
    STORED TTU PARENT and per userset member, so the workload has to have many of
    them: gdrive's `can_read` reverse fan-in (doc -> parent folder chain -> group
    usersets) is that shape, and `lookup_reverse` is expand + rendering.
    """
    _banner(f'set-expand — gdrive/set:roaring scale={scale}, {calls} lookup_reverse '
            f'calls   [R6-2, R6-3]')
    spec = sb.WORKLOADS['gdrive']
    se, ntup = build_set(spec['schema'], spec['shapes'], RoaringSets, spec['gen'](scale))
    qs = spec['reverses'](scale, calls)
    print(f'  dataset: {ntup:,} raw tuples, {len(se.interner.key_of):,} interned keys')

    def work():
        n = 0
        for (rel, ot, on) in qs:
            n += sb._rsz(se.lookup_reverse(rel, ot, on))
        return n

    total, stats, table = _profile(work)
    rows = _rows(stats)
    wall = max(ct for (_n, _t, ct) in rows.values()) if rows else 0.0

    uni_n, uni_t, uni_c = _find(rows, func='union', file_frag='setengine/memberset.py')
    star_n, star_t, star_c = _find(rows, func='_starpop', file_frag='setengine/memberset.py')
    norm_n, norm_t, norm_c = _find(rows, func='_normalize', file_frag='setengine/memberset.py')
    ext_n, ext_t, ext_c = _find(rows, func='_ext', file_frag='setengine/memberset.py')
    inst_n, inst_t, inst_c = _find(rows, func='_instances_of_type', file_frag='setengine/engine.py')

    algebra_t = uni_t + star_t + norm_t + ext_t
    print(f'\n  members returned      : {total:,}')
    print(f'  wall (profiled)       : {wall:.2f} s   ({calls / wall:,.1f} reverses/s under profiler)')
    print(f'  ms.union calls        : {uni_n:,}   self {uni_t:.3f} s')
    print(f'  _starpop calls        : {star_n:,}   self {star_t:.3f} s   ({_pct(star_t, wall)})')
    print(f'  _normalize calls      : {norm_n:,}   self {norm_t:.3f} s')
    print(f'  _ext calls            : {ext_n:,}   self {ext_t:.3f} s')
    print(f'  MemberSet algebra self: {algebra_t:.3f} s  ({_pct(algebra_t, wall)} of expand)')
    print(f'  _instances_of_type    : {inst_n:,} calls, {inst_c:.3f} s cum  ({_pct(inst_c, wall)})')
    print('\n' + table)

    _verdict('R6-2',
             'expand left-folds ms.union, re-materializing the star population per element',
             f'{star_n:,} _starpop calls, algebra self-time {_pct(algebra_t, wall)} of expand',
             algebra_t / wall > 0.25 if wall else None)
    _verdict('R6-3',
             'the interner scan fires on star grants (star-heavy multi-type stores)',
             f'{inst_n:,} calls, {_pct(inst_c, wall)} of expand wall time',
             None if inst_n == 0 else inst_c / wall > 0.10)
    return {'wall': wall, 'starpop': star_n, 'algebra_self': algebra_t}


